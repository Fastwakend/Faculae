import Foundation
import UIKit
import ImageIO
import UniformTypeIdentifiers
import SeekCore
import SeekWebP

/// Binary attachments live outside state.json and never contain credentials.
actor AttachmentStore {
    static let shared = AttachmentStore()
    nonisolated static var folder: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("SeekAPI/Attachments", isDirectory: true)
    }
    nonisolated static func url(for attachment: ChatAttachment) -> URL {
        folder.appendingPathComponent(attachment.id.uuidString)
    }

    func importImage(_ data: Data, name: String = "照片.jpg") throws -> ChatAttachment {
        guard data.count <= AttachmentLimits.fileBytes,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 2048,
                kCGImageSourceCreateThumbnailWithTransform: true
              ] as CFDictionary),
              let jpeg = UIImage(cgImage: image).jpegData(compressionQuality: 0.85) else {
            throw APIError.provider("图片无法读取或过大，请选择其他图片。")
        }
        return try save(jpeg, name: (name as NSString).deletingPathExtension + ".jpg", mime: "image/jpeg", kind: .image)
    }

    func importFile(_ url: URL) throws -> ChatAttachment {
        let scoped = url.startAccessingSecurityScopedResource()
        defer { if scoped { url.stopAccessingSecurityScopedResource() } }
        let size: Int
        do { size = try AttachmentFileIO.size(url) }
        catch { throw APIError.provider("请选择可读取的非空文件，每个文件最多 1 GB。") }
        let type = (try? url.resourceValues(forKeys: [.contentTypeKey]).contentType) ?? UTType(filenameExtension: url.pathExtension)
        if type?.conforms(to: .image) == true {
            guard let source = CGImageSourceCreateWithURL(url as CFURL, [kCGImageSourceShouldCache: false] as CFDictionary),
                  let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceThumbnailMaxPixelSize: 2048,
                    kCGImageSourceCreateThumbnailWithTransform: true
                  ] as CFDictionary), let jpeg = UIImage(cgImage: image).jpegData(compressionQuality: 0.85) else {
                throw APIError.provider("图片无法读取，请选择其他图片。")
            }
            return try save(jpeg, name: url.deletingPathExtension().lastPathComponent + ".jpg", mime: "image/jpeg", kind: .image)
        }
        if type?.conforms(to: .pdf) == true || url.pathExtension.lowercased() == "pdf" {
            let reader = try FileHandle(forReadingFrom: url)
            defer { try? reader.close() }
            guard try reader.read(upToCount: 5) == Data("%PDF-".utf8) else { throw APIError.provider("这个 PDF 文件无法读取。") }
            return try saveFile(url, mime: "application/pdf", kind: .pdf)
        }
        let ext = url.pathExtension.lowercased()
        if size > 1024 * 1024, !DocumentText.officeExtensions.contains(ext), !["html", "htm", "rtf"].contains(ext) {
            guard type?.conforms(to: .text) == true || type?.conforms(to: .json) == true ||
                    ["txt", "md", "csv", "json", "jsonl", "xml", "yaml", "yml", "log", "sql", "py", "js", "swift", "c", "cpp"].contains(ext) else {
                throw APIError.provider("该文件无法提取文字，请使用 PDF、办公文档或文本/代码文件。")
            }
            do { return try saveFile(url, mime: "text/plain", kind: .text, validateText: true) }
            catch let error as CocoaError where error.code == .fileReadInapplicableStringEncoding {
                throw APIError.provider("大文本文件请使用 UTF-8 编码；可先转换编码再添加。")
            }
        }
        if ["rtf", "html", "htm"].contains(ext), size > 16 * 1024 * 1024 {
            throw APIError.provider("此富文本文档的正文过大，请导出为 UTF-8 TXT 或 PDF 后添加。")
        }
        let data = try Data(contentsOf: url, options: .mappedIfSafe)
        let text: String
        if url.pathExtension.lowercased() == "rtf" {
            text = try NSAttributedString(data: data, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil).string
        } else { text = try DocumentText.extract(data, filename: url.lastPathComponent) }
        let normalized = Data(text.utf8)
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, normalized.count <= 1024 * 1024 else {
            throw APIError.provider("文件须有可读取的文字，提取文字最多 1 MB；扫描件请使用图片或 PDF。")
        }
        return try save(normalized, name: url.lastPathComponent, mime: "text/plain", kind: .text)
    }

    /// Preserve original generated bytes whenever possible. Gemini output is
    /// encoded locally to the requested format without downsampling to 2048px.
    func importGeneratedImage(_ data: Data, settings: ImageGenerationSettings, convert: Bool) throws -> ChatAttachment {
        guard !data.isEmpty, data.count <= 134_217_728,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int, let height = props[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= 16384, height <= 16384, width * height <= 40_000_000 else {
            throw APIError.provider("生成的图片无法读取或尺寸过大。")
        }
        let actual = CGImageSourceGetType(source).map { UTType($0 as String) } ?? nil
        let requested = UTType(mimeType: settings.format.mimeType)
        let output: Data
        if !convert, actual == requested { output = data }
        else {
            guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { throw APIError.malformedResponse }
            if settings.format == .webp {
                var pixels = Data(count: width * height * 4)
                output = try pixels.withUnsafeMutableBytes { raw in
                    guard let base = raw.baseAddress,
                          let context = CGContext(data: base, width: width, height: height, bitsPerComponent: 8,
                            bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
                            bitmapInfo: CGBitmapInfo.byteOrder32Big.rawValue | CGImageAlphaInfo.premultipliedLast.rawValue) else {
                        throw APIError.malformedResponse
                    }
                    context.setFillColor(CGColor(gray: 1, alpha: 1)); context.fill(CGRect(x: 0, y: 0, width: width, height: height))
                    context.draw(image, in: CGRect(x: 0, y: 0, width: width, height: height))
                    var encoded: UnsafeMutablePointer<UInt8>?
                    let rgba = base.assumingMemoryBound(to: UInt8.self)
                    let count = settings.compression == nil || settings.compression == 0
                        ? WebPEncodeLosslessRGBA(rgba, Int32(width), Int32(height), Int32(width * 4), &encoded)
                        : WebPEncodeRGBA(rgba, Int32(width), Int32(height), Int32(width * 4), Float(100 - (settings.compression ?? 0)), &encoded)
                    guard count > 0, let encoded else { throw APIError.provider("WebP 图片编码失败。") }
                    defer { WebPFree(encoded) }
                    return Data(bytes: encoded, count: count)
                }
            } else {
                let result = NSMutableData()
                guard let type = requested?.identifier,
                      let destination = CGImageDestinationCreateWithData(result, type as CFString, 1, nil) else { throw APIError.malformedResponse }
                var image = image
                if settings.format == .jpeg || !settings.transparentBackground {
                    guard let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8,
                        bytesPerRow: 0, space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else { throw APIError.malformedResponse }
                    context.setFillColor(CGColor(gray: 1, alpha: 1)); context.fill(CGRect(x: 0, y: 0, width: width, height: height))
                    context.draw(image, in: CGRect(x: 0, y: 0, width: width, height: height))
                    guard let opaque = context.makeImage() else { throw APIError.malformedResponse }; image = opaque
                }
                let quality = Double(100 - (settings.compression ?? 0)) / 100
                CGImageDestinationAddImage(destination, image, [kCGImageDestinationLossyCompressionQuality: quality] as CFDictionary)
                guard CGImageDestinationFinalize(destination) else { throw APIError.provider("图片格式转换失败。") }
                output = result as Data
            }
        }
        try Task.checkCancellation()
        return try save(output, name: "生成图像-" + String(UUID().uuidString.prefix(8)) + "." + settings.format.rawValue,
                        mime: settings.format.mimeType, kind: .image)
    }

    func files(_ messages: [ChatMessage]) throws -> [UUID: URL] {
        var result: [UUID: URL] = [:]
        var total = 0
        for attachment in messages.filter({ $0.isValidContext && $0.imageGenerationSettings == nil }).flatMap({ $0.attachments ?? [] }) {
            guard result[attachment.id] == nil else { continue }
            let url = Self.url(for: attachment)
            guard let size = try? AttachmentFileIO.size(url) else {
                throw APIError.provider("附件“\(attachment.name)”已丢失或无法读取。")
            }
            total += size
            guard total <= AttachmentLimits.batchBytes else { throw APIError.provider("当前请求的附件已超过 6 GB，请新建对话。") }
            result[attachment.id] = url
        }
        return result
    }

    func remove(_ attachments: [ChatAttachment]) {
        for attachment in attachments { try? FileManager.default.removeItem(at: Self.url(for: attachment)) }
    }

    func prune(keeping ids: Set<UUID>) {
        guard let files = try? FileManager.default.contentsOfDirectory(at: Self.folder, includingPropertiesForKeys: nil) else { return }
        for file in files {
            if let id = UUID(uuidString: file.lastPathComponent), !ids.contains(id) { try? FileManager.default.removeItem(at: file) }
        }
    }

    private func save(_ data: Data, name: String, mime: String, kind: ChatAttachment.Kind) throws -> ChatAttachment {
        guard !data.isEmpty, data.count <= AttachmentLimits.fileBytes else { throw APIError.provider("每个附件最多 1 GB。") }
        try FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        var folder = Self.folder
        var flags = URLResourceValues(); flags.isExcludedFromBackup = true
        try folder.setResourceValues(flags)
        let item = ChatAttachment(name: String(name.prefix(160)), mimeType: mime, kind: kind, byteCount: data.count)
        try data.write(to: Self.url(for: item), options: [.atomic, .completeFileProtectionUntilFirstUserAuthentication])
        return item
    }

    private func saveFile(_ url: URL, mime: String, kind: ChatAttachment.Kind, validateText: Bool = false) throws -> ChatAttachment {
        try FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        var folder = Self.folder
        var flags = URLResourceValues(); flags.isExcludedFromBackup = true
        try folder.setResourceValues(flags)
        var item = ChatAttachment(name: String(url.lastPathComponent.prefix(160)), mimeType: mime, kind: kind, byteCount: 0)
        let target = Self.url(for: item)
        do {
            item.byteCount = try AttachmentFileIO.copy(url, to: target, validateText: validateText)
            try FileManager.default.setAttributes([.protectionKey: FileProtectionType.completeUntilFirstUserAuthentication], ofItemAtPath: target.path)
            return item
        } catch { try? FileManager.default.removeItem(at: target); throw error }
    }
}
